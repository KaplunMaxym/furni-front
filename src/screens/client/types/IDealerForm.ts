/**
 * Форма створення дилера: дані клієнта і дані входу разом.
 *
 * Одна форма, бо це одна дія. Розділяти на «створити клієнта», а потім
 * «завести користувача» означало б, що між двома кроками в базі може
 * зʼявитись клієнт без входу — з вигляду звичайний, якого потім заведуть
 * удруге.
 */
export interface IDealerForm {
    // клієнт
    lastName: string;
    firstName: string;
    middleName?: string;
    phone?: string;
    email?: string;
    code1C?: string;
    /** Категорія, за якою рахуватимуться його замовлення. Йому не видима. */
    priceCategory: string;

    // вхід
    /** Як підписувати його дії; порожнє — візьметься «Прізвище Імʼя». */
    userName?: string;
    login: string;
    password: string;
}
